"""Importer for the district indicator workbooks (catalogue in app/indicators.py).

Layout expected in each district sheet: a title row, a blank row, then a header row whose first cell is
'District'. Year columns are headed 2000..2025, or '2021 A' in the seasonal workbook.
Summary rows (means, totals, notes) are skipped. Any other unknown name stops the import, so a
misspelled district is never dropped silently.
"""
import re
from pathlib import Path

import openpyxl
from sqlalchemy import insert
from sqlalchemy.orm import Session

from ..districts import load_district_names
from ..indicators import (DATA_DIR, INDICATORS, NATIONAL, NATIONAL_COLUMNS, NATIONAL_SOURCE,
                          SOURCE_NAMES, WORKBOOKS)
from ..models import DataSource, IndicatorValue

HEADER = re.compile(r"^\s*(\d{4})\s*([ABC]?)\s*$")
SUMMARY_PREFIXES = ("mean", "average", "national", "grey", "yellow", "source", "note")


def _get_source(db: Session, name: str, **kw) -> DataSource:
    src = db.query(DataSource).filter_by(name=name).one_or_none()
    if not src:
        src = DataSource(name=name, **kw)
        db.add(src)
        db.flush()
    return src


def read_district_sheet(ws, district_names: set[str]) -> list[tuple[str, int, str, float]]:
    """Return (district, year, season, value) for every number in a district sheet."""
    rows = list(ws.iter_rows(values_only=True))
    header_at = next((i for i, r in enumerate(rows) if r and r[0] is not None
                      and str(r[0]).strip() == "District"), None)
    if header_at is None:
        raise ValueError(f"{ws.title}: no 'District' header row")
    columns = []
    for j, cell in enumerate(rows[header_at][2:], start=2):
        if cell is None:
            continue
        m = HEADER.match(str(cell))
        if not m:
            raise ValueError(f"{ws.title}: unexpected column heading {cell!r}")
        columns.append((j, int(m.group(1)), m.group(2)))

    found = []
    for r in rows[header_at + 1:]:
        if r[0] is None:
            continue
        name = str(r[0]).strip()
        if name not in district_names:
            if name.lower().startswith(SUMMARY_PREFIXES):
                continue
            raise ValueError(f"{ws.title}: unknown district name {name!r}")
        for j, year, season in columns:
            v = r[j] if j < len(r) else None
            if v is None or (isinstance(v, str) and not v.strip()):
                continue
            if isinstance(v, str):
                raise ValueError(f"{ws.title}: text {v!r} where a number is needed ({name}, {year} {season})")
            found.append((name, year, season, float(v)))
    return found


def load_synthetic_workbooks(db: Session, folder: Path = DATA_DIR) -> dict[str, int]:
    """Load the four SYNTHETIC demo workbooks. Safe to run twice: a workbook already loaded is skipped."""
    names = set(load_district_names())
    loaded = {}
    for group, filename in WORKBOOKS.items():
        path = Path(folder) / filename
        if not path.exists():
            raise FileNotFoundError(f"Indicator workbook missing: {path}")
        src = _get_source(
            db, SOURCE_NAMES[group], publisher="Generated by this project (synthetic demo)",
            is_synthetic=True,
            description="SYNTHETIC demonstration values. They are NOT NISR or census statistics and "
                        "must not be used for analysis or reporting. Replace with the real survey tables.",
            transformations="Read from the workbook as published; no values changed.")
        if db.query(IndicatorValue).filter_by(source_id=src.id).first():
            continue
        wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
        rows = []
        for ind in INDICATORS:
            if ind.group != group:
                continue
            for name, year, season, value in read_district_sheet(wb[ind.sheet], names):
                rows.append({"indicator": ind.key, "district": name, "year": year, "season": season,
                             "value": value, "note": None, "source_id": src.id})
        wb.close()
        if rows:
            db.execute(insert(IndicatorValue), rows)
        loaded[group] = len(rows)
    db.commit()
    return loaded


def load_national_figures(db: Session, folder: Path = DATA_DIR) -> int:
    """Load the national agricultural input figures from the 'National' sheet.

    These are NOT marked synthetic: the workbook says they are real national figures and gives a source
    for each row. They are still unverified here, so each row keeps its source note."""
    path = Path(folder) / WORKBOOKS["inputs"]
    src = _get_source(
        db, NATIONAL_SOURCE, publisher="NISR and the press citations given in each row", is_synthetic=False,
        url="https://statistics.gov.rw",
        description="National figures typed into the agricultural inputs workbook from the source named "
                    "in each row. Not independently re-checked; verify each value against the NISR table.",
        transformations="Blank cells skipped. No calculation applied.")
    if db.query(IndicatorValue).filter_by(source_id=src.id).first():
        return 0
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    rows = list(wb["National"].iter_rows(values_only=True))
    wb.close()
    header = [str(h).strip() if h is not None else "" for h in rows[0]]
    col = {h: j for j, h in enumerate(header)}
    out = []
    for r in rows[1:]:
        if r[0] is None:
            continue
        year, season = int(r[0]), str(r[1]).strip()
        note = str(r[col["Source / note"]]) if r[col["Source / note"]] else None
        for header_name, key in NATIONAL_COLUMNS.items():
            v = r[col[header_name]]
            if v is None:
                continue
            out.append({"indicator": key, "district": NATIONAL, "year": year, "season": season,
                        "value": float(v), "note": note, "source_id": src.id})
    if out:
        db.execute(insert(IndicatorValue), out)
    db.commit()
    return len(out)
